"""Build diagram data for each guide.

Usage:  python3 tools/build.py

Reads data/<guide>.json and writes <guide>/cases.js, which the guide's page loads.
Diagrams are computed from the algorithms, so a typo in an algorithm shows up
as a wrong-looking diagram rather than silently mismatching.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import cube  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
GUIDES = {"oll": "OLL_CASES"}


def build(guide, var):
    cases = json.loads((ROOT / "data" / f"{guide}.json").read_text())
    out = []
    for c in cases:
        grid = cube.oll_grid(c["alg"], edges_only=c.get("edgesOnly", False))
        out.append({**c, "grid": grid, "moves": cube.move_count(c["alg"])})
    target = ROOT / guide / "cases.js"
    target.write_text(
        "// Generated by tools/build.py from data/%s.json. Do not edit by hand.\n"
        "window.%s = %s;\n" % (guide, var, json.dumps(out, indent=2, ensure_ascii=False))
    )
    print(f"{guide}: {len(out)} cases -> {target.relative_to(ROOT)}")


if __name__ == "__main__":
    for guide, var in GUIDES.items():
        build(guide, var)
